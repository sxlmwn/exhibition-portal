-- 1. Add requested_stall_id column to vendor_requests table (Nullable)
ALTER TABLE IF EXISTS vendor_requests 
ADD COLUMN IF NOT EXISTS requested_stall_id bigint REFERENCES stall_slots(id) ON DELETE SET NULL;

-- Also add reference_id if not present
ALTER TABLE IF EXISTS vendor_requests 
ADD COLUMN IF NOT EXISTS reference_id text;

-- 2. Ensure RLS is enabled and public anon SELECT is allowed on past_event_stories
ALTER TABLE IF EXISTS past_event_stories ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Allow public read past_event_stories" ON past_event_stories;
CREATE POLICY "Allow public read past_event_stories" 
ON past_event_stories 
FOR SELECT 
TO anon, authenticated 
USING (true);

DROP POLICY IF EXISTS "Allow anon insert past_event_stories" ON past_event_stories;
CREATE POLICY "Allow anon insert past_event_stories" 
ON past_event_stories 
FOR INSERT 
TO anon, authenticated 
WITH CHECK (true);

DROP POLICY IF EXISTS "Allow anon update past_event_stories" ON past_event_stories;
CREATE POLICY "Allow anon update past_event_stories" 
ON past_event_stories 
FOR UPDATE 
TO anon, authenticated 
USING (true);

DROP POLICY IF EXISTS "Allow anon delete past_event_stories" ON past_event_stories;
CREATE POLICY "Allow anon delete past_event_stories" 
ON past_event_stories 
FOR DELETE 
TO anon, authenticated 
USING (true);

