-- 6. Ensure RLS allows public anon INSERT and SELECT on referrals
CREATE TABLE IF NOT EXISTS referrals (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  referrer_name text NOT NULL,
  referrer_phone text NOT NULL,
  referrer_email text,
  referrer_brand text,
  referee_name text NOT NULL,
  referee_phone text NOT NULL,
  referee_brand text NOT NULL,
  referee_category text,
  exhibition_id bigint REFERENCES exhibitions(id) ON DELETE SET NULL,
  incentive_tier text DEFAULT '5% Cash Cashback',
  status text DEFAULT 'pending',
  reference_id text,
  created_at timestamptz DEFAULT now()
);

